import { resolve } from "node:path";
import { defineConfig, loadEnv } from "vite";
import react from "@vitejs/plugin-react";

const pagePaths: Record<string, string> = {
  "index.html": "/",
  "estudio.html": "/estudio.html",
  "servicos.html": "/servicos.html",
  "pacotes.html": "/pacotes.html",
  "contato.html": "/contato.html",
};

export default defineConfig(({ mode }) => {
  const env = loadEnv(mode, process.cwd(), "");
  const siteOrigin = (env.VITE_SITE_ORIGIN ?? "").replace(/\/$/, "");

  return {
    plugins: [
      react(),
      {
        name: "caverna-seo-tags",
        transformIndexHtml(html, context) {
          if (!siteOrigin) return html;
          const fileName = context.filename.split(/[\\/]/).pop() ?? "index.html";
          const canonicalPath = pagePaths[fileName] ?? "/";
          const canonicalUrl = `${siteOrigin}${canonicalPath}`;
          const absoluteLogo = `${siteOrigin}/caverna-cast-logo.png`;
          let output = html.replace(
            /<meta property="og:image" content="[^"]*"\s*\/>/,
            `<meta property="og:image" content="${absoluteLogo}" />`,
          );
          output = output.replace(
            "</head>",
            `    <link rel="canonical" href="${canonicalUrl}" />\n    <meta property="og:url" content="${canonicalUrl}" />\n  </head>`,
          );
          return output;
        },
        closeBundle() {
          // The sitemap is generated by scripts/generate-sitemap.mjs to keep
          // deployments without a configured canonical domain free of fake URLs.
        },
      },
    ],
    build: {
      rolldownOptions: {
        input: {
          main: resolve(process.cwd(), "index.html"),
          studio: resolve(process.cwd(), "estudio.html"),
          services: resolve(process.cwd(), "servicos.html"),
          packages: resolve(process.cwd(), "pacotes.html"),
          contact: resolve(process.cwd(), "contato.html"),
        },
      },
    },
  };
});
